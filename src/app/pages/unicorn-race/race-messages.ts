export const raceTranslations: Record<Locale, Messages> = { en, de, es, fr };
export function raceText(
  locale: Locale,
  key: RaceMessageKey,
  values: Record<string, string | number> = {},
): string {
  return raceTranslations[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}

export const marketTranslations: Record<Locale, Messages> = { en, de, es, fr };

export function marketText(
  locale: Locale,
  key: MarketMessageKey,
  values: Record<string, string | number> = {},
): string {
  return marketTranslations[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}

/** "the apple", capitalised when it starts a sentence. */
export function capitalise(text: string): string {
  return text.charAt(0).toLocaleUpperCase() + text.slice(1);
}

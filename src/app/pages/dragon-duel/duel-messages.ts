export const duelTranslations: Record<Locale, Messages> = { en, de, es, fr };

export function duelText(
  locale: Locale,
  key: DuelMessageKey,
  values: Record<string, string | number> = {},
): string {
  return duelTranslations[locale][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? `{${name}}`),
  );
}

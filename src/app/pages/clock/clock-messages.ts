export const clockTranslations: Record<Locale, Messages> = { en, de, es, fr };

export function clockText(
  locale: Locale,
  key: ClockMessageKey,
  values: Record<string, string | number> = {},
): string {
  return clockTranslations[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}

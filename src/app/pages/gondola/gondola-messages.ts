export const gondolaTranslations: Record<Locale, Messages> = { en, de, es, fr };

export function gondolaText(
  locale: Locale,
  key: GondolaMessageKey,
  values: Record<string, string | number> = {},
): string {
  return gondolaTranslations[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}

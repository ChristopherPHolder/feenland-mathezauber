export const starTranslations: Record<Locale, Messages> = { en, de, es, fr };

export function starText(
  locale: Locale,
  key: StarMessageKey,
  values: Record<string, string | number> = {},
): string {
  return starTranslations[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}

export type CrocMessageKey = keyof CrocMessages;
export function crocText(
  locale: Locale,
  key: CrocMessageKey,
  values: Record<string, number | string> = {},
) {
  return crocMessages[locale][key].replace(/\{(\w+)\}/g, (placeholder, name: string) => {
    const value = values[name];
    return value === undefined
      ? placeholder
      : typeof value === 'number'
        ? new Intl.NumberFormat(locale).format(value)
        : value;
  });
}

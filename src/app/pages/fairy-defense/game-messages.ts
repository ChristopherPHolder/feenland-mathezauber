export type GameMessageKey = keyof GameMessages;
export function gameText(locale: Locale, key: GameMessageKey, values: Record<string, number> = {}) {
  return gameMessages[locale][key].replace(/\{(\w+)\}/g, (placeholder, key: string) =>
    values[key] === undefined ? placeholder : new Intl.NumberFormat(locale).format(values[key]),
  );
}

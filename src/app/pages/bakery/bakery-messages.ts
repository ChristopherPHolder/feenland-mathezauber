export const bakeryTranslations: Record<Locale, Messages> = { en, de, es, fr };

export function bakeryText(
  locale: Locale,
  key: BakeryMessageKey,
  values: Record<string, string | number> = {},
): string {
  return bakeryTranslations[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}

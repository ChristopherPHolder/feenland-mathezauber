export const scalesTranslations: Record<Locale, Messages> = { en, de, es, fr };

export function scalesText(
  locale: Locale,
  key: ScalesMessageKey,
  values: Record<string, string | number> = {},
): string {
  return scalesTranslations[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}

export const hatcheryTranslations: Record<Locale, Messages> = { en, de, es, fr };

export function hatcheryText(
  locale: Locale,
  key: HatcheryMessageKey,
  values: Record<string, string | number> = {},
): string {
  return hatcheryTranslations[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}

export const lockTranslations: Record<Locale, Messages> = { en, de, es, fr };

/** The trick each level teaches, as a message key. */
export const trickKey = (trick: LockTrick): LockMessageKey => trick;

export function lockText(
  locale: Locale,
  key: LockMessageKey,
  values: Record<string, string | number> = {},
): string {
  return lockTranslations[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}
